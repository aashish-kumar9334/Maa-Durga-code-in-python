# ================= FUNCTIONS =================

def move(x, y):
    t.penup()
    t.goto(x, y)
    t.pendown()

def filled_circle(x, y, r, color):
    move(x, y-r)
    t.color(color)
    t.begin_fill()
    t.circle(r)
    t.end_fill()

def polygon(points, color):
    move(*points[0])
    t.color(color)
    t.begin_fill()

    for p in points[1:]:
        t.goto(*p)

    t.goto(*points[0])
    t.end_fill()

def line(points, color, width=3):
    t.color(color)
    t.width(width)
    move(*points[0])

    for p in points[1:]:
        t.goto(*p)

def write(x, y, text, size, color):
    move(x, y)
    t.color(color)
    t.write(
        text,
        align="center",
        font=("Arial", size, "bold")
    )


